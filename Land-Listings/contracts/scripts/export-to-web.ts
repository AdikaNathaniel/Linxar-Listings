// =============================================================================
// Points the website at a deployment: copies the contracts' ADDRESSES and
// ABIs (and the network they're on) into the website.
// =============================================================================
// After `hardhat ignition deploy`, Ignition saves what it deployed in
//   ignition/deployments/chain-<chainId>/
//     deployed_addresses.json   → where each contract lives
//     artifacts/<id>.json       → each contract's ABI (its list of functions)
//     journal.jsonl             → every transaction, including the BLOCK NUMBER
//                                 each contract was deployed in
//
// This script reads those files and writes web/lib/contracts.generated.ts,
// so the website always uses the contracts that were actually deployed.
//
// Usage:  node scripts/export-to-web.ts localhost   (your local chain)
//         node scripts/export-to-web.ts sepolia     (the public testnet)
// Shortcuts: `npm run use:local` / `npm run use:sepolia` switch the website
// between the two, without redeploying anything.
// =============================================================================

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const NETWORKS: Record<string, number> = { localhost: 31337, sepolia: 11155111 };

const networkName = process.argv[2] ?? "localhost";
const chainId = NETWORKS[networkName];
if (!chainId) {
  console.error(`Unknown network "${networkName}". Use one of: ${Object.keys(NETWORKS).join(", ")}`);
  process.exit(1);
}

const contractsDir = path.resolve(import.meta.dirname, "..");
const deploymentDir = path.join(contractsDir, "ignition", "deployments", `chain-${chainId}`);
const addressesFile = path.join(deploymentDir, "deployed_addresses.json");
const journalFile = path.join(deploymentDir, "journal.jsonl");
const outputFile = path.resolve(contractsDir, "..", "web", "lib", "contracts.generated.ts");

if (!existsSync(addressesFile)) {
  console.error(`No ${networkName} deployment found in ${deploymentDir}.`);
  console.error(`Deploy first:  npm run deploy:${networkName === "localhost" ? "local" : networkName}`);
  process.exit(1);
}

// e.g. { "LinXarModule#ListingBoard": "0x…", … }
const addresses: Record<string, string> = JSON.parse(readFileSync(addressesFile, "utf8"));

// The earliest block any of our contracts was deployed in. The website only
// searches event logs from here on, not from the start of the whole chain
// (which on Sepolia would mean millions of blocks).
let deployBlock = Number.MAX_SAFE_INTEGER;
for (const line of readFileSync(journalFile, "utf8").split("\n")) {
  const match = line.match(/"blockNumber":(\d+)/);
  if (match) deployBlock = Math.min(deployBlock, Number(match[1]));
}
if (deployBlock === Number.MAX_SAFE_INTEGER) deployBlock = 0;

let output =
  "// AUTO-GENERATED by contracts/scripts/export-to-web.ts. Do not edit by hand.\n" +
  "// Regenerate with `npm run use:local` / `npm run use:sepolia` (in contracts/).\n\n" +
  `export const NETWORK = "${networkName}";\n` +
  `export const CHAIN_ID = ${chainId};\n` +
  `export const DEPLOY_BLOCK = ${deployBlock}n;\n`;

for (const [deploymentId, address] of Object.entries(addresses)) {
  // "LinXarModule#ListingBoard" → "ListingBoard"
  const contractName = deploymentId.split("#").pop()!;
  const artifact = JSON.parse(
    readFileSync(path.join(deploymentDir, "artifacts", `${deploymentId}.json`), "utf8"),
  );

  // `as const` keeps the exact function names and types, so viem can still
  // catch typos and wrong arguments in the website's code.
  output +=
    `\nexport const ${contractName} = {\n` +
    `  address: "${address}",\n` +
    `  abi: ${JSON.stringify(artifact.abi, null, 2).replaceAll("\n", "\n  ")},\n` +
    `} as const;\n`;

  console.log(`✔ ${contractName} → ${address}`);
}

writeFileSync(outputFile, output);
console.log(`Website now uses: ${networkName} (chain ${chainId}), contracts deployed from block ${deployBlock}`);
